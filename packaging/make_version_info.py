"""Writes packaging/version_info.txt (the Windows "Properties > Details" text) from photolifeboat.__version__,
so the version only ever has to be changed in one place: src/photolifeboat/__init__.py.

An exe with no description looks more suspicious to antivirus guesswork than one that says what it is,
so every build carries this resource (see docs/RELEASING.md)."""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def version() -> str:
    text = (ROOT / "src" / "photolifeboat" / "__init__.py").read_text()
    return re.search(r'__version__\s*=\s*"([^"]+)"', text).group(1)


def numbers(v: str) -> tuple[int, int, int, int]:
    """Windows wants four plain numbers. 0.2.1 -> (0, 2, 1, 0); a .devN or rcN suffix is dropped."""
    parts = [int(x) for x in re.findall(r"\d+", v.split("rc")[0].split(".dev")[0].split("a")[0].split("b")[0])][:3]
    return tuple(parts + [0] * (4 - len(parts)))


def main() -> int:
    v = version()
    n = numbers(v)
    plain = ".".join(str(x) for x in n[:3])
    (ROOT / "packaging" / "version_info.txt").write_text(f"""# Generated by packaging/make_version_info.py from photolifeboat.__version__ ({v}). Do not edit by hand.
VSVersionInfo(
  ffi=FixedFileInfo(filevers={n}, prodvers={n}, mask=0x3f, flags=0x0, OS=0x40004,
                    fileType=0x1, subtype=0x0, date=(0, 0)),
  kids=[
    StringFileInfo([StringTable('040904B0', [
      StringStruct('CompanyName', 'Photo Lifeboat (open source, GPL-3.0)'),
      StringStruct('FileDescription', 'Photo Lifeboat: gets deleted photos back from memory cards, read-only'),
      StringStruct('FileVersion', '{plain}'),
      StringStruct('InternalName', 'PhotoLifeboat'),
      StringStruct('LegalCopyright', 'GPL-3.0. Source: https://github.com/Benjaminwarren1/photo'),
      StringStruct('OriginalFilename', 'PhotoLifeboat.exe'),
      StringStruct('ProductName', 'Photo Lifeboat'),
      StringStruct('ProductVersion', '{v}')])]),
    VarFileInfo([VarStruct('Translation', [1033, 1200])])
  ]
)
""")
    if len(sys.argv) > 1 and sys.argv[1] == "--check-tag":
        tag = sys.argv[2].removeprefix("refs/tags/")
        if tag != f"v{v}":
            print(f"Tag {tag} does not match the version in src/photolifeboat/__init__.py ({v}). "
                  f"Change __version__ to match, or tag v{v}.", file=sys.stderr)
            return 1
    if "--numeric" in sys.argv:
        print(".".join(str(x) for x in n))     # what installers want: four plain numbers
        return 0
    print(v)
    return 0


if __name__ == "__main__":
    sys.exit(main())
